const managedHeader = "# Generated by ai-agent-config. Do not edit directly; edit config/codex-agents/*.toml.\n"

type codexRoleManifest struct {
	MCPServers  []codexMCPServer           `json:"mcp_servers"`
	SkillGroups map[string][]string        `json:"skill_groups"`
	Roles       map[string]codexRoleConfig `json:"roles"`
}

type codexMCPServer struct {
	Name          string            `json:"name"`
	Command       string            `json:"command"`
	Args          []string          `json:"args"`
	EnabledTools  []string          `json:"enabled_tools"`
	DisabledTools []string          `json:"disabled_tools"`
	Env           map[string]string `json:"env"`
}

type codexRoleConfig struct {
	AllowedMCPServers   []string `json:"allowed_mcp_servers"`
	DisabledSkillGroups []string `json:"disabled_skill_groups"`
}

type Config struct {
	RepoRoot        string
	Home            string
	CodexHome       string
	ClaudeHome      string
	OpenCodeHome    string
	AntigravityHome string
	AgentsHome      string
	Out             io.Writer
	Now             func() time.Time
	LookPath        func(string) (string, error)
}

func NewConfig(repoRoot string, out io.Writer) (Config, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return Config{}, err
	}
	if repoRoot == "" {
		repoRoot, err = defaultRepoRoot()
		if err != nil {
			return Config{}, err
		}
	}
	repoRoot, err = filepath.Abs(repoRoot)
	if err != nil {
		return Config{}, err
	}
	if out == nil {
		out = os.Stdout
	}
	antigravityHome := envDefault("ANTIGRAVITY_HOME", "")
	if antigravityHome == "" {
		antigravityHome = envDefault("GEMINI_HOME", filepath.Join(home, ".gemini"))
	}
	return Config{
		RepoRoot:        repoRoot,
		Home:            home,
		CodexHome:       envDefault("CODEX_HOME", filepath.Join(home, ".codex")),
		ClaudeHome:      envDefault("CLAUDE_HOME", filepath.Join(home, ".claude")),
		OpenCodeHome:    envDefault("OPENCODE_HOME", filepath.Join(home, ".config", "opencode")),
		AntigravityHome: antigravityHome,
		AgentsHome:      envDefault("AGENTS_HOME", filepath.Join(home, ".agents")),
		Out:             out,
		Now:             time.Now,
		LookPath:        exec.LookPath,
	}, nil
}

func (c Config) Install() error {
	c.println("Installing AI agent configuration...")
	c.printf("Config directory: %s\n", c.RepoRoot)
	c.println("")
	c.println("Creating symlinks...")

	configured := 0
	if dirExists(c.CodexHome) {
		configured++
		if err := c.createSymlink(filepath.Join(c.RepoRoot, "AGENTS.md"), filepath.Join(c.CodexHome, "AGENTS.md")); err != nil {
			return err
		}
	} else {
		c.printf("   - Codex home not found, skipping: %s\n", c.CodexHome)
	}
	if dirExists(c.ClaudeHome) {
		configured++
		if err := c.createSkillSymlinks(filepath.Join(c.RepoRoot, "skills"), filepath.Join(c.ClaudeHome, "skills")); err != nil {
			return err
		}
		if err := c.createSymlink(filepath.Join(c.RepoRoot, "CLAUDE.md"), filepath.Join(c.ClaudeHome, "CLAUDE.md")); err != nil {
			return err
		}
	} else {
		c.printf("   - Claude home not found, skipping: %s\n", c.ClaudeHome)
	}
	if dirExists(c.OpenCodeHome) {
		configured++
		if err := c.createSkillSymlinks(filepath.Join(c.RepoRoot, "skills"), filepath.Join(c.OpenCodeHome, "skills")); err != nil {
			return err
		}
		if err := c.createSymlink(filepath.Join(c.RepoRoot, "AGENTS.md"), filepath.Join(c.OpenCodeHome, "AGENTS.md")); err != nil {
			return err
		}
		c.printOpenCodeSlimSkillSetup()
	} else {
		c.printf("   - OpenCode home not found, skipping: %s\n", c.OpenCodeHome)
	}
	if dirExists(c.AntigravityHome) {
		configured++
		if err := c.createSkillSymlinks(filepath.Join(c.RepoRoot, "skills"), filepath.Join(c.AntigravityHome, "antigravity-cli", "skills")); err != nil {
			return err
		}
		if err := c.createSymlink(filepath.Join(c.RepoRoot, "AGENTS.md"), filepath.Join(c.AntigravityHome, "GEMINI.md")); err != nil {
			return err
		}
	} else {
		c.printf("   - Antigravity CLI/Gemini home not found, skipping: %s\n", c.AntigravityHome)
	}

	c.println("")
	if configured == 0 {
		c.println("Warning: no supported home directories were found. No symlinks were created.")
	}
	if dirExists(c.CodexHome) {
		c.println("")
		if err := c.SetupCodexConfig(); err != nil {
			c.println("Warning: Codex base config setup failed; continuing with agent and shell setup.")
			c.println("         Run scripts/setup_codex_config.sh after resolving the reported config issue.")
		}
		c.println("")
		if err := c.SetupCodexAgents(); err != nil {
			return err
		}
		c.println("")
		if err := c.SetupCodexShell(); err != nil {
			return err
		}
		c.println("")
		if err := c.SetupCodexHooks(); err != nil {
			return err
		}
	}
	if dirExists(c.ClaudeHome) {
		c.println("")
		if err := c.SetupClaudeAgents(); err != nil {
			return err
		}
	}
	c.println("Installation complete.")
	c.println("")
	c.println("Next steps:")
	c.println("   1. Read README.md for usage.")
	c.println("   2. Update skills and config/codex-agents as needed.")
	c.println("   3. Run this script again after pulling updates.")
	return nil
}

