func (c Config) prepareCodexAgentDir(targetDir string) (bool, error) {
	legacySource := filepath.Join(c.RepoRoot, "agents")
	info, err := os.Lstat(targetDir)
	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			current, err := os.Readlink(targetDir)
			if err != nil {
				return false, err
			}
			if current == legacySource {
				c.printf("   ! Legacy Codex agents symlink detected: %s -> %s\n", targetDir, current)
				c.println("     Remove that symlink and rerun install.sh so standalone agent TOML files can be generated into ~/.codex/agents/.")
				return false, nil
			}
		} else if !info.IsDir() {
			c.printf("   ! Target exists and is not a directory: %s\n", targetDir)
			c.println("     Skipping standalone Codex agent sync.")
			return false, nil
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	return true, os.MkdirAll(targetDir, 0o755)
}

func (c Config) prepareClaudeAgentDir(targetDir string) (bool, error) {
	source := filepath.Join(c.RepoRoot, "claude-agents")
	info, err := os.Lstat(targetDir)
	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			current, err := os.Readlink(targetDir)
			if err != nil {
				return false, err
			}
			if current == source {
				if err := os.Remove(targetDir); err != nil {
					return false, err
				}
				if err := os.MkdirAll(targetDir, 0o755); err != nil {
					return false, err
				}
				c.printf("   + Migrated directory symlink to real directory: %s\n", targetDir)
				return true, nil
			}
			c.printf("   ! Claude agents symlink exists with different source: %s -> %s\n", targetDir, current)
			c.println("     Skipping per-file sync to avoid overwrite.")
			return false, nil
		}
		if !info.IsDir() {
			c.printf("   ! Target exists and is not a directory: %s\n", targetDir)
			c.println("     Skipping Claude agent sync.")
			return false, nil
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	return true, os.MkdirAll(targetDir, 0o755)
}

func (c Config) generateCodexRoleFiles(targetDir string) error {
	sourceDir := filepath.Join(c.RepoRoot, "config", "codex-agents")
	manifest, err := loadCodexRoleManifest(filepath.Join(sourceDir, "role-manifest.json"))
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(sourceDir)
	if err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".toml" {
			continue
		}
		source := filepath.Join(sourceDir, entry.Name())
		target := filepath.Join(targetDir, entry.Name())
		roleName := strings.TrimSuffix(entry.Name(), filepath.Ext(entry.Name()))
		rendered, err := c.renderRoleTemplate(source, roleName, manifest)
		if err != nil {
			return err
		}
		if ok, err := c.canWriteGeneratedRole(target, sourceDir); err != nil {
			return err
		} else if !ok {
			continue
		}
		if current, err := os.ReadFile(target); err == nil && bytes.Equal(current, rendered) {
			c.printf("   = Role file already current: %s\n", target)
			continue
		}
		if err := os.WriteFile(target, rendered, 0o644); err != nil {
			return err
		}
		c.printf("   + Generated role file: %s\n", target)
	}
	return nil
}

func (c Config) renderRoleTemplate(path, roleName string, manifest codexRoleManifest) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if strings.Contains(string(raw), "[mcp_servers.") {
		return nil, fmt.Errorf("%s contains [mcp_servers.*]; edit config/codex-agents/role-manifest.json instead", path)
	}
	if strings.Contains(string(raw), "[[skills.config]]") {
		return nil, fmt.Errorf("%s contains [[skills.config]]; edit config/codex-agents/role-manifest.json instead", path)
	}
	replacements := map[string]string{
		"{{HOME}}":        c.Home,
		"{{CODEX_HOME}}":  c.CodexHome,
		"{{AGENTS_HOME}}": c.AgentsHome,
		"{{REPO_ROOT}}":   c.RepoRoot,
	}
	text := string(raw)
	if declaredName, ok := roleNameFromTemplate(text); ok && declaredName != roleName {
		return nil, fmt.Errorf("%s declares role name %q, expected %q", path, declaredName, roleName)
	}
	text = renderPlaceholders(text, replacements)
	mcpServers, err := c.renderRoleMCPServers(roleName, manifest)
	if err != nil {
		return nil, err
	}
	skillToggles, err := manifest.renderRoleSkillToggles(roleName, replacements)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(managedHeader)
	out.WriteString(strings.TrimRight(text, "\n"))
	if mcpServers != "" {
		out.WriteString("\n\n")
		out.WriteString(mcpServers)
	}
	if skillToggles != "" {
		out.WriteString("\n\n")
		out.WriteString(skillToggles)
	}
	out.WriteString("\n")
	return out.Bytes(), nil
}

func loadCodexRoleManifest(path string) (codexRoleManifest, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return codexRoleManifest{}, err
	}
	var manifest codexRoleManifest
	if err := json.Unmarshal(raw, &manifest); err != nil {
		return codexRoleManifest{}, fmt.Errorf("parse %s: %w", path, err)
	}
	if err := manifest.validate(); err != nil {
		return codexRoleManifest{}, fmt.Errorf("validate %s: %w", path, err)
	}
	return manifest, nil
}

func (m codexRoleManifest) validate() error {
	mcpNames := map[string]bool{}
	for _, server := range m.MCPServers {
		if strings.TrimSpace(server.Name) == "" {
			return errors.New("mcp server names must not be empty")
		}
		if mcpNames[server.Name] {
			return fmt.Errorf("duplicate mcp server %q", server.Name)
		}
		mcpNames[server.Name] = true
		if strings.TrimSpace(server.Command) == "" {
			return fmt.Errorf("mcp server %q command must not be empty", server.Name)
		}
	}
	if len(m.SkillGroups) == 0 {
		return errors.New("skill_groups must not be empty")
	}
	for groupName, paths := range m.SkillGroups {
		if strings.TrimSpace(groupName) == "" {
			return errors.New("skill group names must not be empty")
		}
		if len(paths) == 0 {
			return fmt.Errorf("skill group %q must contain at least one path", groupName)
		}
		for _, path := range paths {
			if strings.TrimSpace(path) == "" {
				return fmt.Errorf("skill group %q contains an empty path", groupName)
			}
		}
	}
	for roleName, role := range m.Roles {
		if strings.TrimSpace(roleName) == "" {
			return errors.New("role names must not be empty")
		}
		for _, serverName := range role.AllowedMCPServers {
			if !mcpNames[serverName] {
				return fmt.Errorf("role %q references unknown mcp server %q", roleName, serverName)
			}
		}
		for _, groupName := range role.DisabledSkillGroups {
			if _, ok := m.SkillGroups[groupName]; !ok {
				return fmt.Errorf("role %q references unknown skill group %q", roleName, groupName)
			}
		}
	}
	return nil
}

func (c Config) renderRoleMCPServers(roleName string, manifest codexRoleManifest) (string, error) {
	if len(manifest.MCPServers) == 0 {
		return "", nil
	}
	role := manifest.Roles[roleName]
	allowed := map[string]bool{}
	for _, name := range role.AllowedMCPServers {
		allowed[name] = true
	}
	var out bytes.Buffer
	for _, server := range manifest.MCPServers {
		if out.Len() > 0 {
			out.WriteString("\n\n")
		}
		out.WriteString(fmt.Sprintf("[mcp_servers.%s]\n", server.Name))
		out.WriteString(fmt.Sprintf("args = [%s]\n", quoteTOMLStrings(server.Args)))
		out.WriteString(fmt.Sprintf("command = %q\n", server.Command))
		out.WriteString(fmt.Sprintf("enabled = %v", allowed[server.Name] && c.commandAvailable(server.Command) && c.mcpConfigured(server.Name)))
		if len(server.EnabledTools) > 0 {
			out.WriteString(fmt.Sprintf("\nenabled_tools = [%s]", quoteTOMLStrings(server.EnabledTools)))
		}
		if len(server.DisabledTools) > 0 {
			out.WriteString(fmt.Sprintf("\ndisabled_tools = [%s]", quoteTOMLStrings(server.DisabledTools)))
		}
		if len(server.Env) > 0 {
			out.WriteString("\n\n")
			out.WriteString(fmt.Sprintf("[mcp_servers.%s.env]\n", server.Name))
			keys := make([]string, 0, len(server.Env))
			for key := range server.Env {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			for index, key := range keys {
				if index > 0 {
					out.WriteString("\n")
				}
				out.WriteString(fmt.Sprintf("%s = %q", key, server.Env[key]))
			}
		}
	}
	return out.String(), nil
}

