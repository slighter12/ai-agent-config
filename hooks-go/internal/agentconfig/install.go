func tomlTableName(line string) (string, bool) {
	if strings.HasPrefix(line, "[[") || !strings.HasPrefix(line, "[") || !strings.HasSuffix(line, "]") {
		return "", false
	}
	table := strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(line, "["), "]"))
	return table, table != ""
}

func (m codexRoleManifest) renderRoleSkillToggles(roleName string, replacements map[string]string) (string, error) {
	role, ok := m.Roles[roleName]
	if !ok || len(role.DisabledSkillGroups) == 0 {
		return "", nil
	}
	var out bytes.Buffer
	for _, groupName := range role.DisabledSkillGroups {
		paths := m.SkillGroups[groupName]
		for _, path := range paths {
			if out.Len() > 0 {
				out.WriteString("\n\n")
			}
			out.WriteString("[[skills.config]]\n")
			out.WriteString(fmt.Sprintf("path = %q\n", renderPlaceholders(path, replacements)))
			out.WriteString("enabled = false")
		}
	}
	return out.String(), nil
}

func quoteTOMLStrings(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return strings.Join(quoted, ", ")
}

func renderPlaceholders(text string, replacements map[string]string) string {
	for old, newValue := range replacements {
		text = strings.ReplaceAll(text, old, filepath.ToSlash(newValue))
	}
	return text
}

func roleNameFromTemplate(text string) (string, bool) {
	for _, line := range strings.Split(text, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "name") {
			continue
		}
		parts := strings.SplitN(trimmed, "=", 2)
		if len(parts) != 2 || strings.TrimSpace(parts[0]) != "name" {
			continue
		}
		value := strings.TrimSpace(parts[1])
		if len(value) >= 2 && value[0] == '"' && value[len(value)-1] == '"' {
			return value[1 : len(value)-1], true
		}
	}
	return "", false
}

func (c Config) canWriteGeneratedRole(target, sourceDir string) (bool, error) {
	info, err := os.Lstat(target)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return true, nil
		}
		return false, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		current, err := os.Readlink(target)
		if err != nil {
			return false, err
		}
		if filepath.Dir(current) == sourceDir {
			if err := os.Remove(target); err != nil {
				return false, err
			}
			return true, nil
		}
		c.printf("   ! Role symlink exists with different source: %s -> %s\n", target, current)
		c.println("     Skipping to avoid overwrite.")
		return false, nil
	}
	if info.IsDir() {
		c.printf("   ! Role target exists and is a directory: %s\n", target)
		c.println("     Skipping to avoid overwrite.")
		return false, nil
	}
	raw, err := os.ReadFile(target)
	if err != nil {
		return false, err
	}
	if bytes.HasPrefix(raw, []byte(managedHeader)) {
		return true, nil
	}
	c.printf("   ! Role target exists and is not managed by this installer: %s\n", target)
	c.println("     Skipping to avoid overwrite.")
	return false, nil
}

func (c Config) appendZshrcSource(path string) error {
	const sourceLine = `[[ -r "$HOME/.codex/shell/codex-profile-auto.zsh" ]] && source "$HOME/.codex/shell/codex-profile-auto.zsh"`
	raw, err := os.ReadFile(path)
	if err != nil {
		if !errors.Is(err, os.ErrNotExist) {
			return err
		}
		raw = nil
	}
	if bytes.Contains(raw, []byte("codex-profile-auto.zsh")) {
		c.println("   = ~/.zshrc already sources Codex shell helper")
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	if len(raw) > 0 && !bytes.HasSuffix(raw, []byte("\n")) {
		if _, err := f.WriteString("\n"); err != nil {
			return err
		}
	}
	_, err = f.WriteString("\n# Codex repo-managed shell helpers\n" + sourceLine + "\n")
	if err != nil {
		return err
	}
	c.println("   + Added Codex shell helper source to ~/.zshrc")
	return nil
}

