func (c Config) createSymlink(source, target string) error {
	if _, err := os.Lstat(source); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			c.printf("   ! Source not found, skipping: %s\n", source)
			return nil
		}
		return err
	}
	info, err := os.Lstat(target)
	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			current, err := os.Readlink(target)
			if err != nil {
				return err
			}
			if current == source {
				c.printf("   = Symlink already correct: %s\n", target)
			} else {
				c.printf("   ! Symlink exists with different source: %s -> %s\n", target, current)
				c.println("     Skipping to avoid overwrite.")
			}
			return nil
		}
		c.printf("   ! Target exists and is not a symlink: %s\n", target)
		c.println("     Skipping to avoid overwrite.")
		return nil
	}
	if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	if err := os.Symlink(source, target); err != nil {
		return err
	}
	c.printf("   + Created symlink: %s -> %s\n", target, source)
	return nil
}

func (c Config) createSkillSymlinks(sourceDir, targetDir string) error {
	if !dirExists(sourceDir) {
		c.printf("   ! Skills source directory not found, skipping: %s\n", sourceDir)
		return nil
	}
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(sourceDir)
	if err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
	for _, entry := range entries {
		source := filepath.Join(sourceDir, entry.Name())
		if !entry.IsDir() || !fileExists(filepath.Join(source, "SKILL.md")) {
			c.printf("   - Skipping non-skill entry: %s\n", source)
			continue
		}
		if err := c.createSymlink(source, filepath.Join(targetDir, entry.Name())); err != nil {
			return err
		}
	}
	return nil
}

